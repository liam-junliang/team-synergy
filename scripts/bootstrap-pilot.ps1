# Bootstrap the pilot backlog through core-api (dogfooding: platform manages itself).
# Prereq: PowerShell 7+ (pwsh), built tsp CLI, and a running core-api.
# PS 5.x mangles native args (quotes/spaces); run from repo root.
# Usage: pwsh -File scripts/bootstrap-pilot.ps1

$ErrorActionPreference = 'Stop'
if ($PSVersionTable.PSVersion.Major -lt 7) {
  throw 'bootstrap-pilot.ps1 requires PowerShell 7+ (pwsh). PS 5.x cannot pass JSON args reliably.'
}
$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$env:ACP_API_URL = if ($env:ACP_API_URL) { $env:ACP_API_URL } else { 'http://127.0.0.1:8080' }

function Invoke-AgentCtl {
  param([string[]]$CmdArgs)
  $raw = & node (Join-Path $repoRoot 'apps\cli\dist\index.js') @CmdArgs
  if ($LASTEXITCODE -ne 0) { throw "tsp failed: $($CmdArgs -join ' ')" }
  return ($raw | ConvertFrom-Json)
}

Write-Host '== 0. team + project (codes are generated by the service) =='
$team = Invoke-AgentCtl @('team', 'create', '--name', 'Team Synergy Pilot')
$teamCode = $team.data.team_code
$project = Invoke-AgentCtl @('project', 'create', '--name', 'Team Synergy', '--team', $teamCode)
$projectCode = $project.data.project_code
Invoke-AgentCtl @('project', 'bind', $projectCode) | Out-Null

Write-Host '== 1. optional member =='
if ($env:ACP_PILOT_MEMBER_CODE) {
  Invoke-AgentCtl @('team', 'add', $teamCode, $env:ACP_PILOT_MEMBER_CODE, '--role', 'member') | Out-Null
}

Write-Host '== 2. feature =='
$feature = Invoke-AgentCtl @('feature', 'create', '--project', $projectCode, '--title', 'Spike 1 rest: routes / workbenches / defect')
$featureCode = $feature.data.feature_code

Write-Host '== 3. tasks (docs/20 remainder as real tasks) =='
$ac107 = '[{"id":"AC-1","text":"GET /tasks returns task list"},{"id":"AC-2","text":"claim route reuses application use cases"}]'
Invoke-AgentCtl @('task', 'create', '--feature', $featureCode, '--title', 'core-api HTTP task routes (LAN sharing)', '--profile', 'builder', '--source', 'requirement', '--acceptance', $ac107) | Out-Null

$ac108 = '[{"id":"AC-1","text":"three workbench pages render real data"},{"id":"AC-2","text":"orchestration thread + Cytoscape.js graph interactive"}]'
Invoke-AgentCtl @('task', 'create', '--feature', $featureCode, '--title', 'Requirement/Orchestration/Acceptance workbenches', '--profile', 'builder', '--source', 'requirement', '--acceptance', $ac108) | Out-Null

$ac109 = '[{"id":"AC-1","text":"defect report to regression verification loop"},{"id":"AC-2","text":"task source classification queryable end to end"}]'
Invoke-AgentCtl @('task', 'create', '--feature', $featureCode, '--title', 'Defect loop and task source classification', '--profile', 'builder', '--source', 'requirement', '--acceptance', $ac109) | Out-Null

$ac110 = '[{"id":"AC-1","text":"single command starts agent execution loop"}]'
Invoke-AgentCtl @('task', 'create', '--feature', $featureCode, '--title', 'tsp run wrapper (claim then codex then submit)', '--profile', 'builder', '--source', 'ad-hoc', '--acceptance', $ac110) | Out-Null

Write-Host '== 4. board =='
Invoke-AgentCtl @('task', 'list') | ConvertTo-Json -Depth 8

Write-Host "== done. api: $env:ACP_API_URL =="
