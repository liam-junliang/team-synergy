-- Revocations and the credential update commit together for every password replacement path.
CREATE FUNCTION tsp_revoke_remote_mcp_on_account_change() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    revoked_at_time timestamptz := clock_timestamp();
BEGIN
    UPDATE public.remote_mcp_grants SET revoked_at = revoked_at_time
        WHERE principal_id = NEW.id AND revoked_at IS NULL AND expires_at > revoked_at_time;
    DELETE FROM public.remote_mcp_oauth_requests WHERE principal_id = NEW.id;
    RETURN NEW;
END;
$$;
