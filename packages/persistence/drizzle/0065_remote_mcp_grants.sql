CREATE TRIGGER trg_users_revoke_remote_mcp
    AFTER UPDATE OF password_hash, must_change_password, status, deleted_at ON users
    FOR EACH ROW WHEN (
        OLD.password_hash IS DISTINCT FROM NEW.password_hash
        OR (NOT OLD.must_change_password AND NEW.must_change_password)
        OR (OLD.status = 'active' AND NEW.status <> 'active')
        OR (OLD.deleted_at IS NULL AND NEW.deleted_at IS NOT NULL)
    )
    EXECUTE FUNCTION tsp_revoke_remote_mcp_on_account_change();
