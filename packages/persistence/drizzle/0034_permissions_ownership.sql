CREATE TABLE ownership_transfers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar(20) NOT NULL DEFAULT acp_generate_public_code(),
  scope text NOT NULL CHECK (scope IN ('team','project')),
  scope_id bigint NOT NULL,
  from_principal_id bigint NOT NULL,
  to_principal_id bigint NOT NULL,
  initiated_by bigint NOT NULL,
  is_recovery boolean NOT NULL DEFAULT false,
  reason text,
  status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','accepted','cancelled')),
  created_at text NOT NULL,
  expires_at text NOT NULL,
  completed_at text,
  CONSTRAINT ck_ownership_transfers_code CHECK(code ~ '^[0-9A-HJKMNP-TV-Z]{20}$')
);
CREATE UNIQUE INDEX uq_ownership_transfers_code ON ownership_transfers(code);
