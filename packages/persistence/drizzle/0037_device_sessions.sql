 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code varchar(20) NOT NULL DEFAULT acp_generate_public_code(),
 device_id bigint NOT NULL,
 token_hash text NOT NULL,
 created_at text NOT NULL,
 expires_at text,
 revoked_at text,
 CONSTRAINT uq_device_sessions_code UNIQUE(code),
 CONSTRAINT ck_device_sessions_code CHECK(code ~ '^[0-9A-HJKMNP-TV-Z]{20}$'),
 CONSTRAINT uq_device_sessions_token UNIQUE(token_hash)
);
CREATE INDEX idx_device_sessions_device ON device_sessions(device_id);
