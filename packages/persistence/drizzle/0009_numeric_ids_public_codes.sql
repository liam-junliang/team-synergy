CREATE OR REPLACE FUNCTION acp_public_code_from_bytes(source bytea)
RETURNS varchar(20)
LANGUAGE plpgsql
IMMUTABLE
STRICT
AS $$
DECLARE
  alphabet constant text := '0123456789ABCDEFGHJKMNPQRSTVWXYZ';
  buffer bigint := 0;
  bits integer := 0;
  result text := '';
  idx integer;
  current_byte integer;
BEGIN
  IF octet_length(source) < 13 THEN
    RAISE EXCEPTION 'public code requires at least 13 random bytes';
  END IF;

  FOR idx IN 0..octet_length(source) - 1 LOOP
    current_byte := get_byte(source, idx);
    buffer := (buffer << 8) + current_byte;
    bits := bits + 8;

    WHILE bits >= 5 AND char_length(result) < 20 LOOP
      bits := bits - 5;
      result := result || substr(alphabet, ((((buffer >> bits) & 31) + 1)::integer), 1);
      IF bits = 0 THEN
        buffer := 0;
      ELSE
        buffer := buffer & ((1::bigint << bits) - 1);
      END IF;
    END LOOP;

    IF char_length(result) = 20 THEN
      RETURN result::varchar(20);
    END IF;
  END LOOP;

  RAISE EXCEPTION 'insufficient entropy to produce a 20-character public code';
END
$$;
