CREATE TABLE system_agent_jobs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar(20) NOT NULL DEFAULT acp_generate_public_code(),
  project_id bigint NOT NULL,
  document_id bigint NOT NULL,
  requester_id bigint NOT NULL,
  request_key text NOT NULL,
  request_hash text NOT NULL,
  base_revision integer NOT NULL CHECK (base_revision > 0),
  base_title text NOT NULL,
  base_summary text NOT NULL,
  base_content text NOT NULL,
  instruction text NOT NULL,
  quote text,
  status text NOT NULL DEFAULT 'queued' CHECK (status IN ('queued', 'running', 'awaiting_review', 'applied', 'rejected', 'failed', 'cancelled')),
  proposal_json text,
  proposal_hash text,
  quality_json text,
  executor_id text,
  execution_metadata_json text,
  execution_token text,
  lease_expires_at text,
  error text,
  applied_revision integer,
  applied_by bigint,
  created_at text NOT NULL,
  updated_at text NOT NULL,
  CONSTRAINT ck_system_agent_jobs_code CHECK (code ~ '^[0-9A-HJKMNP-TV-Z]{20}$')
);
CREATE UNIQUE INDEX uq_system_agent_jobs_code ON system_agent_jobs(code);
CREATE UNIQUE INDEX uq_system_agent_jobs_request ON system_agent_jobs(project_id, requester_id, request_key);
CREATE INDEX idx_system_agent_jobs_queue ON system_agent_jobs(status, created_at);
CREATE INDEX idx_system_agent_jobs_requester ON system_agent_jobs(project_id, requester_id, created_at);
