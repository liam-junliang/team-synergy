CREATE TABLE code_hosted_analysis_jobs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code varchar(20) NOT NULL DEFAULT acp_generate_public_code() UNIQUE CHECK (code ~ '^[0-9A-HJKMNP-TV-Z]{20}$'),
 project_id bigint NOT NULL REFERENCES projects(id) ON DELETE RESTRICT,
 repository_id bigint NOT NULL REFERENCES project_repositories(id) ON DELETE RESTRICT,
 requester_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 request_key text NOT NULL, request_hash text NOT NULL,
 source_remote_url text NOT NULL, source_branch text NOT NULL,
 status text NOT NULL DEFAULT 'queued' CHECK (status IN ('queued','running','succeeded','failed')),
 run_code varchar(20) REFERENCES code_understanding_runs(code) ON DELETE RESTRICT,
 executor_id text, execution_token text, lease_expires_at text, completion_token_hash text,
 execution_metadata_json text, error text, created_at text NOT NULL, updated_at text NOT NULL,
 CONSTRAINT ck_code_hosted_lease CHECK (
  (status = 'running' AND executor_id IS NOT NULL AND execution_token IS NOT NULL AND lease_expires_at IS NOT NULL)
  OR (status <> 'running' AND execution_token IS NULL AND lease_expires_at IS NULL)
 ),
 CONSTRAINT uq_code_hosted_request UNIQUE(project_id,requester_id,request_key,repository_id),
 CONSTRAINT uq_code_hosted_run UNIQUE(run_code)
);
CREATE UNIQUE INDEX uq_code_hosted_active_repository ON code_hosted_analysis_jobs(repository_id) WHERE status IN ('queued','running');
CREATE INDEX idx_code_hosted_queue ON code_hosted_analysis_jobs(status,id);
