-- Items can only be assembled in the transaction that creates their header.
-- There is no later publish/update operation that can append to a frozen set.
CREATE FUNCTION acp_insert_requirement_baseline_item() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM requirement_baselines b
    WHERE b.id = NEW.baseline_id AND b.xmin::text = (txid_current() % 4294967296)::text
  ) THEN
    RAISE EXCEPTION 'Cannot append to a frozen requirement baseline';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER insert_requirement_baseline_item BEFORE INSERT ON requirement_baseline_items
FOR EACH ROW EXECUTE FUNCTION acp_insert_requirement_baseline_item();
