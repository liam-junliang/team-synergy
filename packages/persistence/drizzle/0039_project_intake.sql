CREATE TABLE intake_batches (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar(20) NOT NULL DEFAULT acp_generate_public_code(),
  project_id bigint NOT NULL, repository_id bigint NOT NULL, namespace text NOT NULL,
  created_by bigint NOT NULL, source_json text NOT NULL, payload_hash text NOT NULL,
  submit_key text NOT NULL, submit_hash text NOT NULL,
  status text NOT NULL CHECK (status IN ('draft','ready','applying','applied','partial','cancelled','stopped')),
  revision integer NOT NULL DEFAULT 1 CHECK (revision > 0), plan_hash text,
  stop_requested boolean NOT NULL DEFAULT false, created_at text NOT NULL, updated_at text NOT NULL,
  CONSTRAINT ck_intake_batches_code CHECK (code ~ '^[0-9A-HJKMNP-TV-Z]{20}$')
);
CREATE UNIQUE INDEX uq_intake_batches_code ON intake_batches(code);
CREATE INDEX idx_intake_batches_project ON intake_batches(project_id);
CREATE UNIQUE INDEX uq_intake_batches_submit ON intake_batches(project_id,created_by,submit_key);
CREATE TABLE intake_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, batch_id bigint NOT NULL,
  item_key text NOT NULL, kind text NOT NULL CHECK(kind IN ('module','feature','requirement_document','requirement','architecture')),
  item_json text NOT NULL, decision_json text,
  status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','applied','bound','skipped','failed','blocked')),
  target_code text, error text
);
CREATE UNIQUE INDEX uq_intake_items_key ON intake_items(batch_id,item_key);
CREATE TABLE intake_bindings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id bigint NOT NULL, repository_id bigint NOT NULL,
  namespace text NOT NULL, kind text NOT NULL, source_key text NOT NULL,
  target_code text NOT NULL, target_fingerprint text NOT NULL, batch_id bigint NOT NULL, created_at text NOT NULL
);
CREATE UNIQUE INDEX uq_intake_bindings_source ON intake_bindings(project_id,repository_id,namespace,kind,source_key);
CREATE TABLE intake_attempts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, batch_id bigint NOT NULL, idempotency_key text NOT NULL,
  plan_hash text NOT NULL, principal_id bigint NOT NULL,
  status text NOT NULL CHECK(status IN ('running','completed','stopped')),
  results_json text NOT NULL DEFAULT '[]', created_at text NOT NULL, finished_at text
);
CREATE UNIQUE INDEX uq_intake_attempts_request ON intake_attempts(batch_id,idempotency_key);
CREATE UNIQUE INDEX uq_intake_attempts_running ON intake_attempts(batch_id) WHERE status='running';
